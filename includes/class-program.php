    public static function get_program(): array {
        $auto_times    = get_option( 'sta_program_times_auto', [] ); // generated by extract_heat_times
        $manual_times  = get_option( 'sta_program_times', [] );      // set by admin per event
        $session_times = get_option( 'sta_program_session_times', [] );
        $para_checked  = get_option( 'sta_program_para', null );
        $session_names = get_option( 'sta_program_session_names', [] ); // eigen sessienamen per sessie-sleutel

        $api_data = get_option( 'sta_swimrankings_program', [] );
        $program  = self::from_api_import( $api_data );

        foreach ( $program as &$e ) {
            $key      = self::event_key( $e );
            $sess_key = self::session_key( $e );

            // Eigen sessienaam (Programma-admin): vervangt het automatische label overal.
            $e['session_label_default'] = $e['session_label'] ?? '';
            $e['session_label_custom']  = false;
            if ( ! empty( $session_names[ $sess_key ] ) ) {
                $e['session_label']        = (string) $session_names[ $sess_key ];
                $e['session_label_custom'] = true;
            }

            // Auto-times (bc/a finals derived from heat scheduling): approx_time only
            if ( isset( $auto_times[ $key ] ) && $auto_times[ $key ] !== '' ) {
                if ( empty( $e['approx_time'] ) ) {
                    $e['approx_time'] = sanitize_text_field( $auto_times[ $key ] );
                }
            }

            // Admin session-level time: approx_time only (never individual start_time)
            if ( isset( $session_times[ $sess_key ] ) ) {
                $e['approx_time'] = sanitize_text_field( $session_times[ $sess_key ] );
            }

            // Manual per-event time: individual start_time
            if ( isset( $manual_times[ $key ] ) ) {
                $e['start_time'] = sanitize_text_field( $manual_times[ $key ] );
            }

            if ( $para_checked !== null ) {
                $e['paralympic'] = in_array( $key, $para_checked, true );
            }
        }
        unset( $e );

        // Migration guard: if ≥2 events in the same date+session_slug all share the same start_time,
        // it was auto-generated by old code (bulk-assigned session start). Move to approx_time.
        // Grouped by session_slug (not the raw SwimRankings session number) so events from
        // different SwimRankings sessions that share the same slug are compared together.
        // A single event with a unique time is always a real individual time — never demote it.
        $sess_uniform = []; // slug_key → shared time, or false if times differ
        $sess_count   = []; // slug_key → count of events with non-empty start_time
        foreach ( $program as $e ) {
            $slug_key = $e['date'] . '|' . ( $e['session_slug'] ?? $e['session'] );
            $t        = $e['start_time'];
            if ( $t === '' ) continue;
            $sess_count[ $slug_key ] = ( $sess_count[ $slug_key ] ?? 0 ) + 1;
            if ( ! array_key_exists( $slug_key, $sess_uniform ) ) {
                $sess_uniform[ $slug_key ] = $t;
            } elseif ( $sess_uniform[ $slug_key ] !== $t ) {
                $sess_uniform[ $slug_key ] = false;
            }
        }
        foreach ( $program as &$e ) {
            $slug_key = $e['date'] . '|' . ( $e['session_slug'] ?? $e['session'] );
            $unified  = $sess_uniform[ $slug_key ] ?? false;
            $count    = $sess_count[ $slug_key ] ?? 0;
            if ( $unified !== false && $count >= 2 ) {
                if ( empty( $e['approx_time'] ) ) {
                    $e['approx_time'] = $unified;
                }
                $e['start_time'] = '';
            }
        }
        unset( $e );

        return $program;
    }

    public static function session_key( array $e ): string {
        return $e['date'] . '|' . $e['session'];
    }

    /**
     * Zet sta_swimrankings_program om naar intern programma-formaat.
     *
     * Bucketing: (datum, round_code, afstand, slag, geslacht).
     * Age-badges: verzameld van ALLE valid events per bucket; onderdrukt bij series.
     * Para-badges: onderdrukt bij series; extra Pass 3 propageert para-vlag
     *   naar semis/finals wanneer een para-event in dezelfde API-sessie zit.
     */
    private static function active_preset(): array {
        $presets = class_exists( 'STA_Admin_SwimRankings' )
            ? STA_Admin_SwimRankings::get_presets()
            : get_option( 'sta_presets', [] );
        $active  = get_option( 'sta_active_preset', '' );
        $preset  = $presets[ $active ] ?? reset( $presets ) ?: [];
        // Normalize any Dutch-language values that may be stored in old presets.
        $nl_en = [
            'A Finales' => 'A Finals', 'B & C Finales' => 'B/C Finals', 'B/C Finales' => 'B/C Finals',
            'Finales' => 'Finals', 'Halve finales' => 'Semifinals', 'Series' => 'Heats',
            'Dames' => 'Women', 'Heren' => 'Men',
        ];
        foreach ( [ 'bc_finals_label', 'a_finals_label' ] as $k ) {
            if ( isset( $preset[ $k ], $nl_en[ $preset[ $k ] ] ) ) {
                $preset[ $k ] = $nl_en[ $preset[ $k ] ];
            }
        }

        return array_merge( [
            // Session type detection (regex against session name)
            'session_heats'         => 'series|voorronde|heat',
            'session_semis'         => 'halve.finale',
            'session_finals'        => 'finale',
            // Relay display labels per gender — must match WordPress taxonomy term names
            'relay_f'               => 'Dames',
            'relay_m'               => 'Heren',
            'relay_x'               => 'Mixed',
            // Age/para badge rules
            'senior_pattern'        => 'senior|open|absoluut|master|elite|para',
            'para_keyword'          => 'para',  // regex: agegroup matching this → para event
            'show_age_in_heats'     => false,   // when false: suppress age badge in series if senior co-exists
            'relay_separate_by_age' => true,    // when true: Onder-18 relay gets separate bucket/page
            // Finals-split: when true, one API finals-session → two visual blocks (bc_finals + a_finals)
            'split_finals_rounds'   => false,
            'bc_finals_round'       => '9',     // round_code for B/C finals (e.g. '9' for Swimming Trials)
            'bc_finals_label'       => 'B/C Finals',
            'a_finals_label'        => 'A Finals',
            // Optional label overrides: map original API session name → display label
            // e.g. ["NJK lange afstanden" => "NJK Lange Afstanden"]
            'session_label_overrides' => [],
            // Round codes to skip entirely when the session type is 'heats'.
            // Use this to exclude swim-offs (round='3' in a round='2' series session).
            'heats_exclude_rounds'    => [],
            // When true: U18 events (gender_code 11/12) share the same program entry as
            // seniors and their event_ids + times are collected. Enable for NK sprint where
            // U18 and seniors swim in separate but combined heats within the same session.
            'u18_shared_heats'        => false,
        ], $preset );
    }

    private static function from_api_import( array $api_events ): array {
        $preset      = self::active_preset();
        $round_slug  = [ '1' => 'finals', '2' => 'semis', '3' => 'heats', '4' => 'heats' ];
        $round_label = [ '1' => 'Finals', '2' => 'Semifinals', '3' => 'Heats', '4' => 'Heats' ];

        $stroke_en_map = [
            '1' => 'Freestyle', '2' => 'Backstroke', '3' => 'Breaststroke',
            '4' => 'Butterfly', '5' => 'Individual Medley',
            '6' => 'Freestyle', '7' => 'Medley',
        ];

        $day_names = [
            1 => 'Monday', 2 => 'Tuesday', 3 => 'Wednesday', 4 => 'Thursday',
            5 => 'Friday', 6 => 'Saturday', 7 => 'Sunday',
        ];

        $gender_base = function( string $code ): string {
            if ( $code === '3' || $code === '0' ) return 'x';
            return substr( $code, -1 ) === '2' ? 'f' : 'm';
        };

        usort( $api_events, function( $a, $b ) {
            $d = strcmp( $a['date'] ?? '', $b['date'] ?? '' );
            if ( $d !== 0 ) return $d;
            // Sort by session start time so afternoon sessions (NJK) stay after morning sessions,
            // regardless of their session_id magnitude.
            $t = strcmp( $a['session_time'] ?? '', $b['session_time'] ?? '' );
            if ( $t !== 0 ) return $t;
            $s = ( $a['session'] ?? 0 ) - ( $b['session'] ?? 0 );
            if ( $s !== 0 ) return $s;
            return ( $a['number'] ?? 0 ) - ( $b['number'] ?? 0 );
        } );

        $relay_gender_labels    = [ 'f' => $preset['relay_f'], 'm' => $preset['relay_m'], 'x' => $preset['relay_x'] ];
        $senior_pattern         = $preset['senior_pattern'];
        $para_keyword           = $preset['para_keyword'];
        $show_age_in_heats      = (bool) $preset['show_age_in_heats'];
        $relay_separate_by_age  = (bool) $preset['relay_separate_by_age'];
        $pat_heats              = $preset['session_heats'];
        $pat_semis              = $preset['session_semis'];
        $pat_finals             = $preset['session_finals'];
        $split_finals_rounds    = (bool) $preset['split_finals_rounds'];
        $bc_finals_round        = $preset['bc_finals_round'];
        $bc_finals_label        = $preset['bc_finals_label'];
        $a_finals_label         = $preset['a_finals_label'];

        // ── Pass 1: bucket by (date, round_code, dist, stroke, gender) ─────────
        // Relay events also include a normalized age-suffix in the key so that
        // an "Onder 18" relay and a "Senioren" relay of the same gender get
        // separate program entries and separate taxonomy pages.
        $buckets = [];
        foreach ( $api_events as $e ) {
            $date       = $e['date']        ?? '';
            $dist_raw   = $e['distance']    ?? '';
            $round_code = $e['round_code']  ?? '3';
            $stroke_c   = $e['stroke_code'] ?? '';
            $gender_c   = (string)( $e['gender_code'] ?? '1' );
            $agegroup   = $e['agegroup']    ?? '';

            if ( ! $date || ! $dist_raw ) continue;

            $g        = $gender_base( $gender_c );
            $is_relay = ! empty( $e['is_relay'] ) || strpos( $dist_raw, 'x' ) !== false;
            $is_para  = preg_match( '/' . $para_keyword . '/i', $agegroup ) === 1;

            // For relay: include age-group in key so different age categories get
            // separate buckets and separate taxonomy pages. Controlled by preset flag.
            $age_key = '';
            if ( $is_relay && ! $is_para && $relay_separate_by_age ) {
                $age_key = preg_match( '/' . $senior_pattern . '/i', $agegroup ) ? '' : $agegroup;
            }

            $key = implode( '|', [ $date, $round_code, $dist_raw, $stroke_c, $g, $age_key ] );
            $buckets[ $key ][ $is_para ? 'para' : 'valid' ][] = $e;
        }

        // ── Pass 2: one program entry per bucket ─────────────────────────────
        $program        = [];
        $session_orders = [];

        foreach ( $buckets as $key => $sides ) {
            $valids = $sides['valid'] ?? [];
            $paras  = $sides['para']  ?? [];

            if ( empty( $valids ) ) continue; // pure-para bucket → skip

            usort( $valids, fn( $a, $b ) => ( $a['number'] ?? 0 ) - ( $b['number'] ?? 0 ) );
            $primary  = $valids[0];
            $all_eids = $preset['u18_shared_heats']
                ? array_values( array_unique( array_filter( array_column( $valids, 'event_id' ) ) ) )
                : array_filter( [ $primary['event_id'] ?? '' ] );

            $date       = $primary['date']         ?? '';
            $dist_raw   = $primary['distance']      ?? '';
            $round_code = $primary['round_code']   ?? '3';
            $stroke_c   = $primary['stroke_code']  ?? '';
            $gender_c   = (string)( $primary['gender_code'] ?? '1' );
            $sess_name  = $primary['session_name'] ?? '';
            $sess_time  = $primary['session_time'] ?? '';
            $stroke     = $stroke_en_map[ $stroke_c ] ?? ( $primary['stroke'] ?? '' );
            $sess_num   = $primary['session']      ?? 1;
            // ?:  so an empty-string session_id falls back to date|num
            $sess_id    = ( $primary['session_id'] ?: ( $date . '|' . $sess_num ) );

            $is_relay = ! empty( $primary['is_relay'] ) || strpos( $dist_raw, 'x' ) !== false;
            $g        = $gender_base( $gender_c );

            // Derive session type from the session name (uses preset patterns).
            // $slug_from_name tracks whether we matched the name (true) or fell back to round_code (false).
            $slug_from_name = true;
            if ( preg_match( '/' . $pat_semis . '/i', $sess_name ) ) {
                $session_slug = 'semis';
            } elseif ( preg_match( '/' . $pat_finals . '/i', $sess_name ) ) {
                $session_slug = 'finals';
            } elseif ( preg_match( '/' . $pat_heats . '/i', $sess_name ) ) {
                $session_slug = 'heats';
            } else {
                $session_slug   = $round_slug[ $round_code ] ?? 'heats';
                $slug_from_name = false;
            }

            // Skip events whose round_code is explicitly excluded for heats sessions
            // (e.g. swim-offs have round='3' in a series session where round='2' is normal).
            if ( $session_slug === 'heats' && ! empty( $preset['heats_exclude_rounds'] ) ) {
                if ( in_array( $round_code, (array) $preset['heats_exclude_rounds'], true ) ) continue;
            }

            // Strip "Sessie N " prefix from display label (e.g. "sessie 1 series" → "Series").
            $display_name  = trim( preg_replace( '/^sessie\s+\d+\s*/i', '', $sess_name ) );
            $display_name  = $display_name ?: ( $round_label[ $round_code ] ?? $sess_name );
            // Allow preset to override any session label by original API name.
            $label_overrides = $preset['session_label_overrides'] ?? [];
            if ( isset( $label_overrides[ $sess_name ] ) ) {
                $display_name = $label_overrides[ $sess_name ];
            }
            // Override with English label based on resolved session type.
            $slug_labels = [ 'heats' => 'Heats', 'semis' => 'Semifinals', 'finals' => 'Finals' ];
            $session_label = $slug_labels[ $session_slug ] ?? $display_name;

            // Collect age categories from ALL valid events in this bucket
            $age_cats = [];
            foreach ( $valids as $ve ) {
                $ag = $ve['agegroup'] ?? '';
                if ( ! empty( $ag ) && ! preg_match( '/' . $senior_pattern . '/i', $ag ) ) {
                    $age_cats[ $ag ] = true;
                }
            }
            $age_cat = implode( ' / ', array_keys( $age_cats ) );

            // Para: any para event in same round/dist/gender bucket
            $is_para = ! empty( $paras );

            // Series: suppress badges when a Senioren/Open entry also swims in this bucket
            // (they all swim together — no label needed). But keep the badge when this bucket
            // contains ONLY an age-specific category (e.g. a standalone Onder 18 relay).
            // Controlled by preset flag show_age_in_heats.
            if ( $session_slug === 'heats' ) {
                $is_para = false; // para badge never shown in series
                if ( ! $show_age_in_heats ) {
                    $has_senior = false;
                    foreach ( $valids as $ve ) {
                        $ag = $ve['agegroup'] ?? '';
                        if ( empty( $ag ) || preg_match( '/' . $senior_pattern . '/i', $ag ) ) {
                            $has_senior = true;
                            break;
                        }
                    }
                    if ( $has_senior ) {
                        $age_cat = ''; // suppress: age group swims alongside Senioren
                    }
                }
            }

            // Earliest (and optionally latest) time across all events in bucket
            $primary_time = '';
            $latest_time  = '';
            $time_pool    = $preset['u18_shared_heats'] ? array_merge( $valids, $paras ) : [ $primary ];
            foreach ( $time_pool as $ev ) {
                $t = $ev['time'] ?? '';
                if ( $t ) {
                    if ( ! $primary_time || strcmp( $t, $primary_time ) < 0 ) $primary_time = $t;
                    if ( ! $latest_time  || strcmp( $t, $latest_time  ) > 0 ) $latest_time  = $t;
                }
            }

            preg_match( '/(\d+)m/', $dist_raw, $m );
            $dist_int = isset( $m[1] ) ? (int) $m[1] : 0;

            $dow      = (int) date( 'N', strtotime( $date ) );
            $day_name = $day_names[ $dow ] ?? $date;

            // Determine which session blocks this entry appears in.
            // Finals-split: only apply when the session name explicitly matched the finals pattern
            // (not when slug was derived from round_code fallback, e.g. NJK sessions).
            $blocks = [];
            if ( $split_finals_rounds && $session_slug === 'finals' && $slug_from_name ) {
                if ( $round_code === $bc_finals_round ) {
                    // B/C + A final coexist in same API event → show in both blocks
                    $blocks[] = [ 'slug' => 'bc_finals', 'sid' => $sess_id . '_bc', 'label' => $bc_finals_label ];
                    $blocks[] = [ 'slug' => 'a_finals',  'sid' => $sess_id . '_a',  'label' => $a_finals_label ];
                } else {
                    // Fastest-heat (800/1500) or relay: only in A finals block
                    $blocks[] = [ 'slug' => 'a_finals',  'sid' => $sess_id . '_a',  'label' => $a_finals_label ];
                }
            } else {
                $blocks[] = [ 'slug' => $session_slug, 'sid' => $sess_id, 'label' => $session_label ];
            }

            foreach ( $blocks as $block ) {
                $b_sess_id    = $block['sid'];
                $b_slug       = $block['slug'];
                $b_label      = $block['label'];
                $session_orders[ $b_sess_id ] = ( $session_orders[ $b_sess_id ] ?? 0 ) + 1;
                $order = $session_orders[ $b_sess_id ];

                $program[] = [
                    'date'          => $date,
                    'day'           => $day_name,
                    'session'       => $b_sess_id,
                    'session_slug'  => $b_slug,
                    'session_label' => ( $split_finals_rounds && $session_slug === 'finals' && $slug_from_name ) ? $b_label : $session_label,
                    'approx_time'   => $sess_time,
                    'order'         => $order,
                    'distance'      => $dist_int,
                    'distance_raw'  => $dist_raw,
                    'stroke'        => $stroke,
                    'stroke_code'   => $stroke_c,
                    'gender'        => $g,
                    'term_name'     => $is_relay
                        ? trim( $dist_raw . ' ' . ( $stroke === 'Individual Medley' ? 'Medley' : $stroke ) . ' ' . ( $relay_gender_labels[ $g ] ?? '' ) . ( $age_cat ? ' ' . $age_cat : '' ) )
                        : $dist_raw . ' ' . $stroke,
                    'relay'         => $is_relay,
                    'paralympic'    => $is_para,
                    'age_category'  => $age_cat,
                    'fastest_heat'  => false,
                    'njk'           => false,
                    'start_time'    => ( $primary_time && $primary_time !== $sess_time ) ? $primary_time : '',
                    'latest_time'   => $latest_time,
                    'event_id'      => $primary['event_id'] ?? '',
                    'event_ids'     => $all_eids,
                    'session_id'    => $b_sess_id,
                ];
            }
        }

        // ── Pass 3: propagate para to semis/finals via session_id matching ────
        // Para events may be stored with round_code='3' even when they are in a
        // halve-finales or finales API session. Detect this by checking whether a
        // para event shares the same session_id as a non-heats valid entry.
        //
        // Build: "session_id|dist|stroke|gender" → true for every para event.
        $session_para = [];
        foreach ( $api_events as $e ) {
            if ( ! preg_match( '/' . $para_keyword . '/i', $e['agegroup'] ?? '' ) ) continue;
            $sess = ( $e['session_id'] ?: ( ( $e['date'] ?? '' ) . '|' . ( $e['session'] ?? 1 ) ) );
            $dist = $e['distance'] ?? '';
            $g    = $gender_base( (string)( $e['gender_code'] ?? '1' ) );
            if ( $dist ) {
                // Key by stroke_code so it matches the stored stroke_code in $entry
                $session_para[ $sess . '|' . $dist . '|' . ( $e['stroke_code'] ?? '' ) . '|' . $g ] = true;
            }
        }

        if ( ! empty( $session_para ) ) {
            foreach ( $program as &$entry ) {
                if ( ( $entry['session_slug'] ?? '' ) === 'heats' ) continue;
                $combo = $entry['session_id'] . '|' . $entry['distance_raw'] . '|' . $entry['stroke_code'] . '|' . $entry['gender'];
                if ( isset( $session_para[ $combo ] ) ) {
                    $entry['paralympic'] = true;
                }
            }
            unset( $entry );
        }

        // ── Pass 4: deduplicate heats — mark later entries (swim-offs) as swimoff=true ─
        // Swim-offs create a second bucket for the same event (different round_code).
        // Keep both but flag duplicates; get_by_day() will hide swimoffs from the schedule.
        $heats_seen = [];
        foreach ( $program as &$entry ) {
            $entry['swimoff'] = false;
            if ( ( $entry['session_slug'] ?? '' ) === 'heats' && ! $entry['relay'] ) {
                $dk = $entry['date'] . '|' . $entry['distance_raw'] . '|' . $entry['stroke_code'] . '|' . $entry['gender'];
                if ( isset( $heats_seen[ $dk ] ) ) {
                    $entry['swimoff'] = true; // hide from program, but keep for results
                } else {
                    $heats_seen[ $dk ] = true;
                }
            }
        }
        unset( $entry );

        // Re-sort: date → session → order
        usort( $program, function( $a, $b ) {
            $d = strcmp( $a['date'], $b['date'] );
            if ( $d !== 0 ) return $d;
            $s = strcmp( $a['session'], $b['session'] );
            if ( $s !== 0 ) return $s;
            return $a['order'] - $b['order'];
        } );

        return $program;
    }

    public static function event_key( array $e ): string {
        return $e['date'] . '|' . $e['session'] . '|' . $e['order'];
    }

    public static function get_entries_for_term( string $term_name, string $gender ): array {
        $result = [];
        $seen   = []; // deduplicate: one heats entry per (date, session_id)
        foreach ( self::get_program() as $e ) {
            if ( $e['term_name'] !== $term_name || $e['gender'] !== $gender ) continue;
            // For heats: skip secondary rounds (swim-offs) that share the same session
            if ( $e['session_slug'] === 'heats' ) {
                $dedup_key = $e['date'] . '|' . ( $e['session_id'] ?? $e['session'] );
                if ( isset( $seen[ $dedup_key ] ) ) continue;
                $seen[ $dedup_key ] = true;
            }
            $result[] = $e;
        }
        // Sort chronologically: date → session start time → slug order (bc_finals before a_finals)
        $slug_rank = [ 'heats' => 0, 'semis' => 1, 'finals' => 2, 'bc_finals' => 2, 'a_finals' => 3 ];
        usort( $result, function( $a, $b ) use ( $slug_rank ) {
            $d = strcmp( $a['date'], $b['date'] );
            if ( $d !== 0 ) return $d;
            $t = strcmp( $a['approx_time'] ?? '', $b['approx_time'] ?? '' );
            if ( $t !== 0 ) return $t;
            return ( $slug_rank[ $a['session_slug'] ] ?? 9 ) - ( $slug_rank[ $b['session_slug'] ] ?? 9 );
        } );
        return $result;
    }

    public static function get_by_day(): array {
        $out = [];
        foreach ( self::get_program() as $e ) {
            if ( ! empty( $e['swimoff'] ) ) continue; // hide swim-offs from schedule
            $date    = $e['date'];
            $sess_id = $e['session'];
            $out[ $date ]['day']  = $e['day'];
            $out[ $date ]['date'] = $date;
            if ( ! isset( $out[ $date ]['sessions'][ $sess_id ] ) ) {
                $slug = $e['session_slug'] ?? $sess_id;
                // Sort key: "HH:MM" from approx_time + slug suffix so bc_finals < a_finals
                $slug_order = [ 'bc_finals' => '0', 'a_finals' => '1' ];
                $sort_key   = ( $e['approx_time'] ?: '99:99' ) . '|' . ( $slug_order[ $slug ] ?? '0' );
                $out[ $date ]['sessions'][ $sess_id ] = [
                    'label'       => $e['session_label'],
                    'label_default' => $e['session_label_default'] ?? $e['session_label'],
                    'label_custom'  => ! empty( $e['session_label_custom'] ),
                    'approx_time' => $e['approx_time'],
                    'slug'        => $slug,
                    'sort_key'    => $sort_key,
                    'events'      => [],
                ];
            }
            $out[ $date ]['sessions'][ $sess_id ]['events'][] = $e;
        }
        // Sort sessions within each day chronologically
        foreach ( $out as &$day ) {
            uasort( $day['sessions'], fn( $a, $b ) => strcmp( $a['sort_key'], $b['sort_key'] ) );
        }
        unset( $day );
        return $out;
    }

    public static function format_date( string $ymd ): string {
        return date( 'l j F', strtotime( $ymd ) );
    }

    public static function ordinal( int $n ): string {
        $s = [ 'th', 'st', 'nd', 'rd' ];
        $v = $n % 100;
        return $n . ( $s[ ( $v - 20 ) % 10 ] ?? $s[ min( $v, 3 ) ] ?? $s[0] );
    }

    private static function default_program(): array {
        return [];
    }
